
  
    

create or replace transient table ATMOSYNC_DB.PUBLIC_RAW_DATA.CLEANED_RAW_IOT_DATA
    
    
    
    as (

WITH ranked_data AS (

    SELECT
        *,
        ROW_NUMBER() OVER (
            PARTITION BY RECORD_ID
            ORDER BY RECORD_ID
        ) AS rn
    FROM IOT_PROJECT.PUBLIC.stg_raw_iot_data

),

deduplicated AS (

    SELECT *
    FROM ranked_data
    WHERE rn = 1
      AND RECORD_ID IS NOT NULL

),

avg_values AS (

    SELECT
        AVG(TEMPERATURE_C) AS AVG_TEMP,
        AVG(HUMIDITY_PERCENT) AS AVG_HUMIDITY,
        AVG(VIBRATION_LEVEL) AS AVG_VIBRATION,
        AVG(MARKET_PRICE_PER_KG) AS AVG_MARKET_PRICE,
        AVG(SPOILAGE_RISK) AS AVG_SPOILAGE_RISK,
        AVG(DISTANCE_TO_MARKET) AS AVG_DISTANCE,
        AVG(TIME_TO_SPOILAGE_HOURS) AS AVG_TIME
    FROM deduplicated

)

SELECT

    d.RECORD_ID,
    d.TIMESTAMP,
    d.CONTAINER_ID,
    d.SHIPMENT_ID,
    d.PRODUCT_NAME,
    d.ORIGIN_CITY,
    d.DESTINATION_CITY,

    COALESCE(d.TEMPERATURE_C, a.AVG_TEMP) AS TEMPERATURE_C,
    COALESCE(d.HUMIDITY_PERCENT, a.AVG_HUMIDITY) AS HUMIDITY_PERCENT,
    COALESCE(d.VIBRATION_LEVEL, a.AVG_VIBRATION) AS VIBRATION_LEVEL,

    d.TRAVEL_DISTANCE_KM,

    COALESCE(d.DISTANCE_TO_MARKET, a.AVG_DISTANCE) AS DISTANCE_TO_MARKET,

    COALESCE(d.TIME_TO_SPOILAGE_HOURS, a.AVG_TIME) AS TIME_TO_SPOILAGE_HOURS,

    d.SHELF_LIFE_REMAINING_HOURS,

    COALESCE(d.SPOILAGE_RISK, a.AVG_SPOILAGE_RISK) AS SPOILAGE_RISK,

    d.QUALITY_SCORE,

    d.PRODUCT_WEIGHT_KG,

    COALESCE(d.MARKET_PRICE_PER_KG, a.AVG_MARKET_PRICE) AS MARKET_PRICE_PER_KG,

    d.ESTIMATED_REVENUE,
    d.ESTIMATED_LOSS,
    d.ARBITRAGE_PROFIT,
    d.RECOMMENDED_ACTION,
    d.ALERT_LEVEL,

    CASE
        WHEN COALESCE(d.SPOILAGE_RISK, a.AVG_SPOILAGE_RISK) >= 70 THEN 'HIGH'
        WHEN COALESCE(d.SPOILAGE_RISK, a.AVG_SPOILAGE_RISK) >= 40 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS RISK_CATEGORY

FROM deduplicated d
CROSS JOIN avg_values a
    )
;


  